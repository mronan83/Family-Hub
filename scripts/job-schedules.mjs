#!/usr/bin/env node
// Job schedules as code (01 §5.6, D-38). Reads apps/web/lib/jobs/schedule.json and prints the SQL the
// deploy runs after the smoke check: pg_cron jobs named familywise-<name> (created, updated, and
// removed when no longer listed) and the private.job_schedule rows job_health reads. Only jobs with
// the familywise- prefix are touched. `--check` validates without printing.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

export const SCHEDULE_PATH = join(
  dirname(fileURLToPath(import.meta.url)),
  '../apps/web/lib/jobs/schedule.json',
);
const PREFIX = 'familywise-';
const TAG = '$job$';

export function loadSchedule(path = SCHEDULE_PATH) {
  return JSON.parse(readFileSync(path, 'utf8')).jobs;
}

/** The minutes (0–59) a cron expression's minute field fires on. */
export function minutesOf(cron) {
  const field = cron.trim().split(/\s+/)[0];
  const minutes = new Set();
  for (const part of field.split(',')) {
    const [range, step = '1'] = part.split('/');
    const [lo, hi] = range === '*' ? [0, 59] : range.split('-').map(Number);
    const end = hi ?? (part.includes('/') ? 59 : lo);
    for (let m = lo; m <= end; m += Number(step)) minutes.add(m);
  }
  return minutes;
}

/** Problems with the schedule, as messages; empty when it is valid. */
export function validate(jobs) {
  const errors = [];
  const names = new Set();
  const cronField = /^(\*|\d+(-\d+)?)(\/\d+)?(,(\*|\d+(-\d+)?)(\/\d+)?)*$/;
  for (const job of jobs) {
    const where = `job "${job.name}"`;
    if (!/^[a-z][a-z0-9_]*$/.test(job.name ?? '')) errors.push(`${where}: name must be snake_case`);
    if (names.has(job.name)) errors.push(`${where}: listed twice`);
    names.add(job.name);
    const fields = (job.cron ?? '').trim().split(/\s+/);
    if (fields.length !== 5 || !fields.every((f) => cronField.test(f))) {
      errors.push(`${where}: cron must have five fields of digits, *, ranges, steps or lists`);
    } else if ([...minutesOf(job.cron)].some((m) => m < 0 || m > 59 || Number.isNaN(m))) {
      errors.push(`${where}: cron minutes must be 0 to 59`);
    }
    if (!Number.isInteger(job.everyMinutes) || job.everyMinutes <= 0)
      errors.push(`${where}: everyMinutes must be a positive whole number`);
    if (job.kind === 'http') {
      if (job.sql) errors.push(`${where}: an http job has no sql`);
    } else if (job.kind === 'sql') {
      if (!job.sql) errors.push(`${where}: a sql job needs sql`);
      else if (job.sql.includes(TAG)) errors.push(`${where}: sql must not contain ${TAG}`);
    } else {
      errors.push(`${where}: kind must be http or sql`);
    }
  }
  // Calls that start together each pay a cold start and queue behind each other in pg_net (SPIKE-05).
  const http = jobs.filter(
    (j) => j.kind === 'http' && j.cron && !errors.some((e) => e.includes(`"${j.name}"`)),
  );
  for (let i = 0; i < http.length; i++) {
    for (let k = i + 1; k < http.length; k++) {
      const shared = [...minutesOf(http[i].cron)].filter((m) => minutesOf(http[k].cron).has(m));
      if (shared.length)
        errors.push(
          `jobs "${http[i].name}" and "${http[k].name}" share minute(s) ${shared.join(', ')}`,
        );
    }
  }
  return errors;
}

const literal = (s) => `'${String(s).replaceAll("'", "''")}'`;

/** The SQL that makes pg_cron and private.job_schedule match the schedule. */
export function schedulesSql(jobs) {
  const errors = validate(jobs);
  if (errors.length) throw new Error(`invalid job schedule:\n- ${errors.join('\n- ')}`);
  const names = jobs.map((j) => literal(j.name)).join(', ');
  const cronNames = jobs.map((j) => literal(PREFIX + j.name)).join(', ');
  const lines = [
    '-- Generated by scripts/job-schedules.mjs from apps/web/lib/jobs/schedule.json.',
    'insert into private.job_schedule (job_type, cron, kind, every_minutes, updated_at) values',
    jobs
      .map(
        (j) =>
          `  (${literal(j.name)}, ${literal(j.cron)}, ${literal(j.kind)}, ${j.everyMinutes}, now())`,
      )
      .join(',\n'),
    'on conflict (job_type) do update set cron = excluded.cron, kind = excluded.kind,',
    '  every_minutes = excluded.every_minutes, updated_at = excluded.updated_at;',
    `delete from private.job_schedule where job_type not in (${names});`,
  ];
  for (const j of jobs) {
    const command = j.kind === 'http' ? `select private.call_job(${literal(j.name)})` : j.sql;
    lines.push(
      `select cron.schedule(${literal(PREFIX + j.name)}, ${literal(j.cron)}, ${TAG}${command}${TAG});`,
    );
  }
  lines.push(
    `select cron.unschedule(jobid) from cron.job where jobname like '${PREFIX}%' and jobname not in (${cronNames});`,
  );
  return lines.join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const jobs = loadSchedule();
  if (process.argv.includes('--check')) {
    const errors = validate(jobs);
    if (errors.length) {
      console.error(`invalid job schedule:\n- ${errors.join('\n- ')}`);
      process.exit(1);
    }
    console.log(`${jobs.length} job schedule(s) valid`);
  } else {
    process.stdout.write(schedulesSql(jobs));
  }
}
